// Generate 20 random questions from alphabet
export function generateQuestions() {
  const shuffled = [...germanAlphabet].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, 20);
}

// Generate wrong answers for a question
export function generateOptions(correctLetter, allLetters) {
  const wrong = allLetters
    .filter((l) => l.letter !== correctLetter.letter)
    .sort(() => Math.random() - 0.5)
    .slice(0, 3);
  
  const options = [...wrong, correctLetter].sort(() => Math.random() - 0.5);
  return options;
}
